-- Experimental Windows Bedrock client plugin. Requires matching LeviLamina/Bedrock SDK.
add_rules("mode.debug", "mode.release")
add_repositories("java-bridge-local .", {rootdir = os.scriptdir()})
add_repositories("levimc-repo https://github.com/LiteLDev/xmake-repo.git")
option("target_type")
    set_default("client")
    set_showmenu(true)
    set_values("client")
option_end()
add_requires("levilamina 26.51.9", {configs = {target_type = "client"}})
add_requires("levibuildscript")
if not has_config("vs_runtime") then set_runtimes("MD") end

target("CFBedrockJavaBridge")
    add_rules("@levibuildscript/linkrule")
    add_rules("@levibuildscript/modpacker")
    add_defines("NOMINMAX", "UNICODE", "_HAS_CXX23=1")
    set_exceptions("none")
    add_cxflags("/EHa", "/utf-8", "/W4")
    set_toolchains("clang-cl")
    add_packages("levilamina")
    add_syslinks("ws2_32")
    set_kind("shared")
    set_languages("c++20")
    set_symbols("debug")
    add_headerfiles("src/**.h")
    add_files("src/**.cpp")
    add_includedirs("src")
