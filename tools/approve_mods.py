#!/usr/bin/env python3
"""Explicitly approve downloaded Java mod bytes before the production launcher executes them.

Review downloaded files yourself: hashing is change detection, not malware scanning.
"""
import argparse
import hashlib
from pathlib import Path


def checksum(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for part in iter(lambda: stream.read(65536), b""):
            digest.update(part)
    return digest.hexdigest()


def approval_lines(mods: Path) -> list[str]:
    if not mods.is_dir():
        raise ValueError(f"Mod directory missing: {mods}")
    jars = sorted(mods.glob("*.jar"))
    if len(jars) > 100:
        raise ValueError("Refusing to approve more than 100 JARs")
    lines = ["# Filename + SHA256 allowlist, tabs separate fields; generated by explicit user approval."]
    for jar in jars:
        if "\t" in jar.name or "\n" in jar.name or "\r" in jar.name or ".." in jar.name:
            raise ValueError(f"Unsafe filename: {jar.name!r}")
        if jar.is_symlink():
            raise ValueError(f"Refusing symlink: {jar.name}")
        lines.append(checksum(jar) + "\t" + jar.name)
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mods", type=Path, default=Path(__file__).resolve().parents[1] / "out/mods")
    parser.add_argument("--output", type=Path, default=None)
    parser.add_argument("--yes", action="store_true", help="I have personally reviewed and trust every JAR in --mods")
    args = parser.parse_args()
    if not args.yes:
        parser.error("Approval is explicit; review JARs, then pass --yes")
    output = args.output or args.mods / "approved-mods.tsv"
    data = "\n".join(approval_lines(args.mods)) + "\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(data, encoding="utf-8")
    print(f"Approved {len(data.splitlines()) - 1} exact JAR files in {output}")
    print("A changed JAR will no longer match its approved hash. Review before re-approving.")


if __name__ == "__main__":
    main()
