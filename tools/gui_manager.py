"""Experimental JavaBridge desktop manager (Windows Tk GUI).

Run from repository root with: python -m tools.gui_manager
This app does not install a Bedrock native DLL or claim mod compatibility.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
from zipfile import is_zipfile

from tools.inspect import inspect_jar

ROOT = Path(__file__).resolve().parents[1]
STAGING = ROOT / "downloaded-curseforge-mods"
MODS = ROOT / "out" / "mods"
APPROVAL = MODS / "approved-mods.tsv"


def safe_name(name: str) -> bool:
    return (bool(name) and len(name) <= 200 and name.lower().endswith(".jar")
            and ".." not in name and not any(c in name for c in "/\\:\r\n\t"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def stage_jar(source: Path, folder: Path = STAGING) -> Path:
    source = Path(source)
    if source.is_symlink() or not source.is_file() or not safe_name(source.name):
        raise ValueError("Unsafe JAR input")
    if source.stat().st_size > 128 * 1024 * 1024 or not is_zipfile(source):
        raise ValueError("JAR is oversized or invalid")
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / source.name
    if target.exists():
        raise FileExistsError("That JAR filename is already staged")
    with tempfile.NamedTemporaryFile(dir=folder, prefix=".stage-", delete=False) as temp:
        pending = Path(temp.name)
        try:
            with source.open("rb") as stream:
                shutil.copyfileobj(stream, temp)
        except Exception:
            pending.unlink(missing_ok=True)
            raise
    pending.replace(target)
    return target


def approve_jar(source: Path, folder: Path = MODS) -> Path:
    """Call only after explicit consent; approval is NOT malware scanning."""
    source = Path(source)
    if source.is_symlink() or not source.is_file() or not safe_name(source.name):
        raise ValueError("Unsafe JAR input")
    if not is_zipfile(source) or source.stat().st_size > 128 * 1024 * 1024:
        raise ValueError("JAR is oversized or invalid")
    folder.mkdir(parents=True, exist_ok=True)
    target = folder / source.name
    if target.exists() and (target.is_symlink() or sha256(target) != sha256(source)):
        raise FileExistsError("Different JAR already exists with this filename")
    if not target.exists():
        shutil.copy2(source, target)
    lock = folder / "approved-mods.tsv"
    entries = {}
    if lock.exists():
        for line in lock.read_text("utf-8").splitlines():
            if line.startswith("#") or not line.strip():
                continue
            pieces = line.split("\t")
            if len(pieces) != 2 or not safe_name(pieces[1]):
                raise ValueError("Existing approval list is malformed")
            entries[pieces[1]] = pieces[0]
    entries[target.name] = sha256(target)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=folder,
                                     prefix=".approvals-", delete=False) as output:
        temporary = Path(output.name)
        output.write("# Explicit SHA-256 approvals generated by the user\n")
        for name in sorted(entries):
            output.write(f"{entries[name]}\t{name}\n")
    temporary.replace(lock)
    return target


def main() -> None:
    import tkinter as tk
    from tkinter import filedialog, messagebox, scrolledtext, ttk
    root = tk.Tk()
    root.title("JavaBridge — CurseForge Java Mod Manager (Experimental)")
    root.geometry("920x640")
    pane = ttk.Frame(root, padding=12)
    pane.pack(fill="both", expand=True)
    ttk.Label(pane, text="JavaBridge", font=("Segoe UI", 18, "bold")).pack(anchor="w")
    ttk.Label(pane, text="Stage, inspect and explicitly approve Java JARs. Bedrock native DLL is not yet verified.").pack(anchor="w")
    selected = tk.Listbox(pane, height=8)
    selected.pack(fill="both", expand=True, pady=8)
    detail = scrolledtext.ScrolledText(pane, height=12, wrap="word")
    detail.pack(fill="both", expand=True, pady=8)
    buttons = ttk.Frame(pane)
    buttons.pack(fill="x", pady=4)
    console = scrolledtext.ScrolledText(pane, height=6, wrap="word")
    console.pack(fill="both", expand=True, pady=8)
    paths: list[Path] = []
    host: subprocess.Popen | None = None

    def write(message: str):
        console.insert("end", message + "\n")
        console.see("end")

    def refresh():
        STAGING.mkdir(parents=True, exist_ok=True)
        paths[:] = sorted(STAGING.glob("*.jar"))
        selected.delete(0, "end")
        for path in paths:
            selected.insert("end", path.name)

    def chosen():
        indices = selected.curselection()
        return paths[indices[0]] if indices else None

    def inspect_selected(_event=None):
        file = chosen()
        if file is None:
            return
        detail.delete("1.0", "end")
        detail.insert("end", json.dumps(inspect_jar(file), indent=2))

    def import_selected():
        file = filedialog.askopenfilename(filetypes=[("Java JARs", "*.jar")])
        if not file:
            return
        try:
            staged = stage_jar(Path(file))
            write("Staged (not approved): " + staged.name)
            refresh()
        except Exception as error:
            messagebox.showerror("Import blocked", str(error))

    def approve_selected():
        file = chosen()
        if not file:
            return
        report = inspect_jar(file)
        approved = messagebox.askyesno(
            "Execute at your own risk",
            f"Java mods run with your OS permissions and are not sandboxed.\n\n"
            f"{file.name}\nSHA-256: {report.get('sha256')}\n"
            f"Compatibility: {report.get('status')}\n\n"
            "Have you reviewed and explicitly approved these exact bytes?")
        if not approved:
            return
        try:
            target = approve_jar(file)
            write("Approved and copied: " + target.name)
        except Exception as error:
            messagebox.showerror("Approval failed", str(error))

    def start_host():
        nonlocal host
        if host is not None and host.poll() is None:
            return
        if not APPROVAL.is_file():
            messagebox.showerror("No approvals", "Approve a reviewed JAR first")
            return
        if not (ROOT / "out/host/bridge/Host.class").exists():
            build = subprocess.run([sys.executable, str(ROOT / "tools/build.py")],
                                   cwd=ROOT, capture_output=True, text=True)
            if build.returncode:
                messagebox.showerror("Build failed", build.stderr[-1500:])
                return
        host = subprocess.Popen([sys.executable, str(ROOT / "tools/start_client_bridge.py"),
                                 "--mods", str(MODS)], cwd=ROOT)
        write("JavaBridge sidecar started. Native Bedrock DLL is a separate requirement.")

    def stop_host():
        nonlocal host
        if host is not None and host.poll() is None:
            host.terminate()
            write("Stopped JavaBridge sidecar.")

    selected.bind("<<ListboxSelect>>", inspect_selected)
    for label, callback in (("Import JAR", import_selected), ("Refresh", refresh),
                            ("Approve selected", approve_selected), ("Start sidecar", start_host),
                            ("Stop sidecar", stop_host)):
        ttk.Button(buttons, text=label, command=callback).pack(side="left", padx=4)
    root.protocol("WM_DELETE_WINDOW", lambda: (stop_host(), root.destroy()))
    refresh()
    root.mainloop()


if __name__ == "__main__":
    main()
